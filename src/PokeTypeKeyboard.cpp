// First 28 bytes of the queue's dequeue routine, checked before every injection.
//
//   6C02  ldr  r2, [r0, #0x40]    ; read index
//   6C41  ldr  r1, [r0, #0x44]    ; write index
//   428A  cmp  r2, r1
//   D101  bne  +2
//   2000  movs r0, #0             ; empty -> return 0
//   4770  bx   lr
//   0091  lsls r1, r2, #2
//   5843  ldr  r3, [r0, r1]       ; event = buf[read]
//   1C52  adds r2, r2, #1
//   210F  movs r1, #0x0F
//   4011  ands r1, r2             ; read = (read+1) & 15
//   6401  str  r1, [r0, #0x40]
//   1C18  mov  r0, r3
//   4770  bx   lr
static const u8 GetInputSignature[] =
{
    0x02, 0x6C, 0x41, 0x6C, 0x8A, 0x42, 0x01, 0xD1, 0x00, 0x20, 0x70, 0x47, 0x91, 0x00,
    0x43, 0x58, 0x52, 0x1C, 0x0F, 0x21, 0x11, 0x40, 0x01, 0x64, 0x18, 0x1C, 0x70, 0x47
};

