bool PokeTypeKeyboard::SetGameCode(u32 gamecode) noexcept
{
    Game = nullptr;

    for (const GameInfo& info : GameTable)
    {
        if (info.GameCode == gamecode)
        {
            Game = &info;
            break;
        }
    }

    return Game != nullptr;
}

bool PokeTypeKeyboard::IsReady() noexcept
{
    if (!Game) return false;

    for (u32 i = 0; i < sizeof(GetInputSignature); i++)
    {
        if (NDS.ARM9Read8(Game->GetInputAddr + i) != GetInputSignature[i])
            return false;
    }

    return true;
}

u8 PokeTypeKeyboard::FindKeyID(u16 character) const noexcept
{
    if (!Game || !Game->Map) return 0xFF;

    s32 min = 0;
    s32 max = (s32)Game->MapLength - 1;

    while (min <= max)
    {
        s32 mid = (min + max) / 2;
        u16 cur = Game->Map[mid].Character;

        if (cur < character)      min = mid + 1;
        else if (cur > character) max = mid - 1;
        else                      return (u8)Game->Map[mid].KeyID;
    }

    return 0xFF;
}

bool PokeTypeKeyboard::PushKey(u16 character, u8 mods) noexcept
{
    if (!Game) return false;

    // the Japanese build wants the bare character
    if (!Game->Map) return PushKeyID(character, 0, mods);

    u8 keyid = FindKeyID(character);
    if (keyid == 0xFF) return false;

    return PushKeyID(character, keyid, mods);
}

bool PokeTypeKeyboard::PushKeyID(u16 character, u8 keyid, u8 mods) noexcept
{
    if (!IsReady()) return false;

    const u32 queue = Game->QueueAddr;

    u32 write = NDS.ARM9Read32(queue + QueueWriteIndex) & QueueMask;
    u32 read  = NDS.ARM9Read32(queue + QueueReadIndex) & QueueMask;
    u32 next  = (write + 1) & QueueMask;

    // queue full -- the game's own enqueue drops the event here too
    if (next == read) return false;

    // same format as the game's own producer at UZPP 0x0205BFD0
    u32 event = Game->Map ? (((u32)mods << 24) | ((u32)keyid << 16) | character)
                          : character;

    NDS.ARM9Write32(queue + (write * 4), event);
    NDS.ARM9Write32(queue + QueueWriteIndex, next);

    // Needed for the game to accept keys when no keyboard was ever connected
    // ("Play without wireless keyboard"). Once the emulated keyboard has
    // connected, or a bonded one is about to reconnect, the driver owns this
    // flag: forcing it then makes the game skip its battery request and show
    // the keyboard as disconnected, or ignore keys at its "press any key" prompt.
    if (!GameHasWirelessKeyboard())
        NDS.ARM9Write8(Game->StateAddr + StateEnable, 1);

    return true;
}

bool PokeTypeKeyboard::GameHasWirelessKeyboard() const noexcept
{
    const NDSCart::CartCommon* cart = NDS.GetNDSCart();
    if (!cart || cart->Type() != NDSCart::CartType::RetailBT) return false;

    return static_cast<const NDSCart::CartRetailBT*>(cart)->GameHasKeyboard();
}

// Keys with no printable character: private-range codes for the modifiers, PC
// extended scancodes for the arrows, control characters for the rest. The same
// in all five European tables and in what the Japanese decoder produces.
static const CharKeyPair SpecialKeys[] =
{
    {0x000D,0x28}, {0x0008,0x2A}, {0x0009,0x2B}, {0x0020,0x2C},
    {0xFF06,0x39}, {0xE04D,0x4F}, {0xE04B,0x50}, {0xE050,0x51},
    {0xE048,0x52}, {0xFF02,0x70}, {0xFF01,0x71}, {0xFF00,0x72},
    {0xFF04,0x73}, {0xFF08,0x74}, {0xFF07,0x75}, {0xFF0B,0x76},
};

const char* PokeTypeKeyboard::RegionCode(Region r) noexcept
{
    switch (r)
    {
    case Region::Europe:  return "EUR";
    case Region::France:  return "FRA";
    case Region::Germany: return "GER";
    case Region::Italy:   return "ITA";
    case Region::Spain:   return "SPA";
    case Region::Japan:   return "JPN";
    default:              return "";
    }
}

const PokeTypeKeyboard::KeyDesc* PokeTypeKeyboard::GetKeyTable(Region r, u32& count) noexcept
{
    for (const GameInfo& info : GameTable)
    {
        if (info.Reg == r)
        {
            count = info.LayoutLength;
            return info.Layout;
        }
    }

    count = 0;
    return nullptr;
}

const PokeTypeKeyboard::CharKeyPair* PokeTypeKeyboard::GetTypingMap(Region r, u32& count) noexcept
{
    for (const GameInfo& info : GameTable)
    {
        if (info.Reg == r)
        {
            count = info.MapLength;
            return info.Map;
        }
    }

    count = 0;
    return nullptr;
}

u16 PokeTypeKeyboard::SpecialCharForKeyID(u16 keyid) noexcept
{
    for (const CharKeyPair& pair : SpecialKeys)
        if (pair.KeyID == keyid)
            return pair.Character;

    return 0;
}

// Caps Lock only swaps base and shift on keys marked caps-sensitive (the letters).
u16 PokeTypeKeyboard::CharForKey(const KeyDesc& key, bool shift, bool altgr,
                                 bool caps) noexcept
{
    bool swap = caps && key.CapsSensitive;

    if (shift && altgr) return key.ShiftAltGr;
    if (altgr)          return key.AltGr;
    if (shift)          return swap ? key.Base : key.Shift;

    return swap ? key.Shift : key.Base;
}

PokeTypeKeyboard::Region PokeTypeKeyboard::GetRegion() const noexcept
{
    return Game ? Game->Reg : Region::MAX;
}

